import type { MultipartFile } from "@api/http/http-client";
import type { MenuLinkListData } from "@api/rest/types/content";
import type { WithRequired } from "@core/required-fields";

import { uniqueId } from "@core/unique-id";

import { SEEDED_LANGUAGE } from "../seeded";

export const FORBIDDEN_EXTENSION = ".exe";
export const FILE_EXTENSIONS_BLACKLIST_SETTING = "VirtoCommerce.Platform.Security.FileExtensionsBlackList";

export function newMarkdownFile(prefix: string): MultipartFile {
  return {
    name: `${uniqueId(prefix)}.en-US.md`,
    mimeType: "text/markdown",
    buffer: Buffer.from("# Test page\n\nGenerated by automated tests.\n"),
  };
}

export function newForbiddenFile(): MultipartFile {
  return {
    name: `${uniqueId("test-forbidden")}${FORBIDDEN_EXTENSION}`,
    mimeType: "application/octet-stream",
    buffer: Buffer.from("MZ test content"),
  };
}

export type MenuLinkListDraft = WithRequired<MenuLinkListData, "id" | "name" | "storeId" | "language">;

export function newMenuLinkList(storeId: string, name = uniqueId("test-menu")): MenuLinkListDraft {
  return {
    id: crypto.randomUUID(),
    name,
    storeId,
    language: SEEDED_LANGUAGE,
    menuLinks: [
      { priority: 10, title: "About us", url: "~/pages/about_us" },
      { priority: 0, title: "Pages", url: "~/pages" },
    ],
  };
}
